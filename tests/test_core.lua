-- Run from the repo root: luajit tests/test_core.lua
local Core = assert(loadfile("CorpseCamp/Core.lua"))()

local passed, failed = 0, 0
local function test(name, fn)
    local ok, err = pcall(fn)
    if ok then passed = passed + 1 else failed = failed + 1 ; print("FAIL " .. name .. ": " .. tostring(err)) end
end
local function eq(actual, expected, what)
    if actual ~= expected then
        error(("%s: expected %s, got %s"):format(what or "value", tostring(expected), tostring(actual)), 2)
    end
end

test("name matching ignores case and a missing realm", function()
    eq(Core.SameName("Gankmaster", "gankmaster"), true)
    eq(Core.SameName("Gankmaster", "Gankmaster-Azjol-Nerub"), true)
    eq(Core.SameName("Gankmaster-Azjol-Nerub", "Gankmaster-AzjolNerub"), true)
    eq(Core.SameName("Gankmaster-Azjol Nerub", "Gankmaster-AzjolNerub"), true)
    eq(Core.SameName("Gankmaster-Firemaw", "Gankmaster-Gehennas"), false)
    eq(Core.SameName("Gankmaster", "Gankmasterr"), false)
    eq(Core.SameName(nil, "Gankmaster"), false)
end)

test("corpse released then seen alive alerts once", function()
    local c = Core.new()
    c:Camp("Rogue", "dead", 0)
    eq(c:Sighting("dead", 1), false, "dead sighting")
    c:NotSeen(5)
    eq(c.state, "gone")
    eq(c:Sighting("alive", 60), true, "first alive sighting")
    eq(c:Sighting("alive", 60.2), false, "duplicate sighting from another event")
    eq(c:Sighting("alive", 61), false, "ticker sighting")
end)

test("in-place resurrection while corpse stays visible alerts", function()
    local c = Core.new()
    c:Camp("Priest", "dead", 0)
    eq(c:Sighting("dead", 10), false)
    eq(c:Sighting("alive", 20), true, "soulstone/res in place")
end)

test("alive sighting alerts even when we never saw the corpse", function()
    local c = Core.new()
    c:Camp("Hunter", "absent", 0)          -- /ccamp Hunter, not visible anywhere
    eq(c:Sighting("alive", 30), true)
end)

test("camping a living target waits for the kill before arming", function()
    local c = Core.new()
    c:Camp("Paladin", "alive", 0)
    eq(c:Sighting("alive", 1), false, "still alive, not a resurrection")
    c:NotSeen(2)
    eq(c:Sighting("alive", 3), false, "walked out of view and back")
    eq(c:Sighting("dead", 10), false, "killed")
    c:NotSeen(11)
    eq(c:Sighting("alive", 70), true, "resurrected")
end)

test("camping a visible target with a hidden life flag does not alert at once", function()
    local c = Core.new()
    c:Camp("Shaman", "unknown", 0)
    eq(c:Sighting("unknown", 0.2), false, "same corpse on the next scan")
    c:NotSeen(5)
    eq(c:Sighting("unknown", 50), true, "reappeared after vanishing")
end)

test("hidden life flag counts as a resurrection only after they were gone", function()
    local c = Core.new()
    c:Camp("Mage", "dead", 0)
    eq(c:Sighting("unknown", 1), false, "corpse still in view, flag hidden")
    c:NotSeen(2)
    eq(c:Sighting("unknown", 40), true, "reappeared after vanishing")
end)

test("being seen dead again re-arms the alert", function()
    local c = Core.new()
    c:Camp("Warrior", "dead", 0)
    c:NotSeen(1)
    eq(c:Sighting("alive", 50), true)
    eq(c:Sighting("dead", 55), false, "killed again")
    c:NotSeen(56)
    eq(c:Sighting("alive", 120), true, "second resurrection")
end)

test("out of view while alive keeps the alert spent", function()
    local c = Core.new()
    c:Camp("Druid", "dead", 0)
    c:NotSeen(1)
    eq(c:Sighting("alive", 10), true)
    c:NotSeen(11)
    eq(c.state, "alive")
    eq(c:Sighting("alive", 12), false)
end)

test("idle core never alerts", function()
    local c = Core.new()
    eq(c:Sighting("alive", 1), false)
    c:NotSeen(2)
    eq(c.state, "idle")
    c:Camp("X", "dead", 0) ; c:Stop()
    eq(c:Sighting("alive", 3), false)
    eq(c:Matches("X"), false)
end)

test("auto-capture does not steal an active camp", function()
    local c = Core.new()
    eq(c:OnKill("First", 0), true, "idle -> camp")
    eq(c:OnKill("First", 1), false, "same corpse rescanned")
    eq(c:OnKill("Second", 2), false, "still waiting on First")
    eq(c.name, "First")
    c:NotSeen(3)
    eq(c:Sighting("alive", 4), true)
    eq(c:OnKill("Second", 5), true, "First already rezzed, switch")
    eq(c.name, "Second")
    eq(c.state, "dead")
end)

test("a kill replaces a camp that was only waiting for a kill", function()
    local c = Core.new()
    c:Camp("Alive", "alive", 0)
    eq(c:OnKill("Other", 1), true)
    eq(c.name, "Other")
    eq(c.state, "dead")
end)

test("status line shows state and elapsed time", function()
    local c = Core.new()
    eq(c:Status(0), nil)
    c:Camp("Rogue", "dead", 0)
    eq(c:Status(12), "Rogue: corpse in view 0:12")
    c:NotSeen(20)
    eq(c:Status(95), "Rogue: ghost or out of view 1:15")
    c:Sighting("alive", 100)
    eq(c:Status(103), "Rogue: RESURRECTED 0:03")
end)

print(("%d passed, %d failed"):format(passed, failed))
os.exit(failed == 0 and 0 or 1)
